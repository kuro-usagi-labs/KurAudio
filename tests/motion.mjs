import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

await fs.mkdir('test-results/motion', { recursive: true });
const browser = await chromium.launch();
let checks = 0;
const check = (ok, name) => { assert.ok(ok, name); console.log(`PASS ${name}`); checks++; };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: 'test-results/motion', size: { width: 1440, height: 900 } } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto('http://127.0.0.1:1422'); await page.getByRole('button', { name: 'Proyek baru', exact: true }).click();
  await page.getByRole('button', { name: 'Buka sesi demo' }).click();
  await page.getByTestId('audio-clip').first().waitFor();
  await page.waitForTimeout(350);
  const snap = page.getByRole('button', { name: 'Snapping (N)', exact: true });
  await snap.hover(); await page.mouse.down(); await page.waitForTimeout(100);
  check(await snap.evaluate(el => Number(getComputedStyle(el).scale) < 0.99), 'press feedback compresses a button without changing layout');
  await page.mouse.up(); await page.waitForTimeout(320);
  check(await snap.evaluate(el => getComputedStyle(el).scale === '1'), 'button settles back after release');
  await page.mouse.down(); await page.mouse.move(1000, 70); await page.mouse.up(); await page.waitForTimeout(320);
  check(await snap.evaluate(el => getComputedStyle(el).scale === '1'), 'pointer cancellation does not leave a button compressed');

  const help = page.getByRole('button', { name: 'Shortcut', exact: true });
  await help.click();
  await page.waitForFunction(() => document.querySelector('.modal')?.getAnimations().some(a => a.transitionProperty === 'scale'));
  check(await page.locator('.modal').evaluate(el => el.getAnimations().some(a => a.transitionProperty === 'translate')), 'dialog enters with a short scale and position transition');
  await page.locator('.modal').evaluate(el => el.getAnimations().forEach(a => { a.pause(); a.currentTime = Number(a.effect.getTiming().duration) / 2; }));
  await page.screenshot({ path: 'test-results/motion/dialog-mid-enter.png' });
  await page.locator('.modal').evaluate(el => el.getAnimations().forEach(a => a.play()));
  await page.waitForTimeout(320);
  await page.keyboard.press('Tab');
  check(await page.evaluate(() => !!document.activeElement.closest('[role=dialog]')), 'dialog keeps keyboard focus inside while open');
  await page.keyboard.press('Escape');
  check(await page.locator('.motion-presence[data-state=exiting] .modal').count() === 1, 'dialog stays mounted for its exit animation');
  check(await page.locator('.motion-presence[data-state=exiting]').evaluate(el => el.inert && el.getAttribute('aria-hidden') === 'true'), 'closing dialog is immediately inert and hidden from assistive technology');
  check(await help.evaluate(el => document.activeElement === el), 'Escape restores focus to the trigger as the dialog closes');
  await page.locator('.modal').waitFor({ state: 'detached' });
  // Reopen during exit: a previous removal timer must never erase the new dialog.
  await help.click(); await page.waitForTimeout(320);
  await page.evaluate(() => document.querySelector('.modal .icon-button').click());
  await page.evaluate(() => document.querySelector('.help-button').click());
  await page.waitForTimeout(350);
  check(await page.getByRole('dialog').count() === 1 && await page.getByRole('dialog').isVisible(), 'rapid close and reopen cancels the old exit timer');
  await page.keyboard.press('Escape'); await page.locator('.modal').waitFor({ state: 'detached' });

  const mediaToggle = page.getByRole('button', { name: 'Tampilkan media', exact: true });
  await mediaToggle.click();
  check(await page.locator('.media-panel').evaluate(el => el.inert), 'collapsed media panel immediately leaves keyboard navigation');
  await page.waitForTimeout(320);
  check(await page.locator('.media-panel').evaluate(el => el.getBoundingClientRect().width < 2), 'media panel collapses its actual grid column');
  await mediaToggle.click(); await page.waitForTimeout(320);
  check(await page.locator('.media-panel').evaluate(el => !el.inert && el.getBoundingClientRect().width > 200), 'media panel reopens to its full layout width');
  await page.getByTestId('audio-clip').first().click({ position: { x: 40, y: 50 } });
  await page.waitForTimeout(320);
  const properties = page.getByRole('button', { name: 'Properti', exact: true });
  await properties.click(); await page.waitForTimeout(320);
  check(await page.locator('.inspector').evaluate(el => el.inert && el.getBoundingClientRect().width < 2), 'inspector collapse removes its content from focus and layout');
  await properties.click(); await page.waitForTimeout(320);
  check(await page.locator('.inspector').evaluate(el => !el.inert && el.getBoundingClientRect().width > 200), 'inspector reopens without losing the selected clip');
  const geometry = await page.getByTestId('audio-clip').first().evaluate(el => getComputedStyle(el).transitionProperty);
  check(!/left|width|transform|translate|all/.test(geometry), 'timeline geometry has no animation delay during drag or trim');
  const fader = page.getByRole('slider', { name: 'Volume Voice over', exact: true });
  await fader.focus(); await page.keyboard.press('ArrowLeft');
  check(await fader.inputValue() === '-1' && await page.locator('.track-gain').first().textContent() === '-1 dB', 'fader changes real gain immediately while its grip feedback animates');

  await page.getByRole('button', { name: 'Ekspor audio', exact: true }).click();
  await page.waitForTimeout(320);
  await page.getByRole('button', { name: '44.1 kHz', exact: true }).click();
  check(await page.getByRole('button', { name: '44.1 kHz', exact: true }).getAttribute('aria-pressed') === 'true', 'sliding export selection commits the actual sample rate immediately');
  await page.waitForTimeout(320);
  await page.getByRole('checkbox', { name: /Normalisasi peak/ }).click();
  await page.waitForTimeout(220);
  check(!(await page.getByRole('checkbox', { name: /Normalisasi peak/ }).isChecked()), 'animated checkbox still changes the normalization setting');
  await page.screenshot({ path: 'test-results/motion/export.png' });
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  await fs.writeFile('test-results/motion/axe.json', JSON.stringify(axe.violations, null, 2));
  check(axe.violations.length === 0, 'animated dialog has no automated WCAG A/AA violations');
  const css = await page.evaluate(() => Array.from(document.styleSheets).flatMap(s => Array.from(s.cssRules).map(r => r.cssText)).join('\n'));
  await fs.writeFile('test-results/motion/harness.html', await page.evaluate(css => '<!doctype html><html lang="id"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>KurAudio motion harness</title><style>' + css + '</style></head><body>' + document.body.innerHTML.replace(/<script[\s\S]*?<\/script>/g, '') + '</body></html>', css));
  await page.keyboard.press('Escape'); await page.locator('.modal').waitFor({ state: 'detached' });

  await page.emulateMedia({ reducedMotion: 'reduce' });
  await snap.hover(); await page.mouse.down();
  check(await snap.evaluate(el => getComputedStyle(el).scale === '1' && getComputedStyle(el).transitionDuration === '0s'), 'Reduce Motion removes press movement and transitions');
  await page.mouse.up();
  await help.click(); await page.waitForTimeout(30);
  check(await page.locator('.modal').evaluate(el => getComputedStyle(el).opacity === '1' && el.getAnimations().length === 0), 'Reduce Motion shows the dialog immediately without hiding content');
  await page.keyboard.press('Escape'); await page.locator('.modal').waitFor({ state: 'detached' });
  check(await help.evaluate(el => document.activeElement === el), 'Reduce Motion preserves dialog dismissal and focus restoration');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await help.click(); await page.emulateMedia({ reducedMotion: 'reduce' }); await page.waitForTimeout(30);
  check(await page.locator('.motion-presence:has(.modal)').getAttribute('data-state') === 'entered', 'changing Reduce Motion during an entrance finishes the pending transition');
  await page.keyboard.press('Escape'); await page.locator('.modal').waitFor({ state: 'detached' });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'motion introduces no document overflow');
  check(errors.length === 0, 'motion and rapid reversals produce no runtime errors');
  await context.close();
  console.log(`RESULT: ${checks} motion checks passed`);
} finally { await browser.close(); }
